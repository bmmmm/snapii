// Text of a run as the user sees it: CSS white-space collapsing,
// text-transform, and the space clean-up where runs of one line meet.
// DOM-free; the content script passes computed style values in.

// white-space (legacy keywords) and white-space-collapse values that keep
// spaces as authored. Everything else collapses.
const PRESERVING = new Set(["pre", "pre-wrap", "break-spaces", "preserve", "preserve-spaces"]);

export function isPreserved(whiteSpace: string): boolean {
  return PRESERVING.has(whiteSpace);
}

// Values that keep segment breaks (newlines) as line breaks.
const BREAKING = new Set(["pre", "pre-wrap", "pre-line", "break-spaces", "preserve", "preserve-breaks"]);

export function keepsBreaks(whiteSpace: string): boolean {
  return BREAKING.has(whiteSpace);
}

/**
 * Collapses one line's slice of a text node like CSS does: runs of
 * [ \t\n\r\f] become one space (normal, nowrap, pre-line). Preserved text
 * stays verbatim except for segment breaks: inside a single line slice a
 * newline can only be the break that ends it, never a glyph.
 */
export function collapse(text: string, whiteSpace: string): string {
  if (isPreserved(whiteSpace)) return text.replace(/[\n\r]/g, "");
  return text.replace(/[ \t\n\r\f]+/g, " ");
}

function upper(s: string, lang: string | null): string {
  try {
    return s.toLocaleUpperCase(lang ?? undefined);
  } catch {
    // Malformed lang attribute: RangeError from the locale lookup.
    return s.toUpperCase();
  }
}

function lower(s: string, lang: string | null): string {
  try {
    return s.toLocaleLowerCase(lang ?? undefined);
  } catch {
    return s.toLowerCase();
  }
}

// [first, last, offset]: capitalize maps each code point in first..last to
// code point + offset, its Unicode titlecase (ǆ -> ǅ, ᾳ -> ᾼ; Georgian
// Mkhedruli and title-case letters stay), where toUpperCase gives Ǆ, ΑΙ or
// Mtavruli. Only the letters both engines title-case, in any language;
// generated by scripts/titlecase.mjs (Unicode 17.0), which says how.
const TITLECASE: readonly (readonly [number, number, number])[] = [
  [0x1c5, 0x1c5, 0],
  [0x1c6, 0x1c6, -1],
  [0x1c8, 0x1c8, 0],
  [0x1c9, 0x1c9, -1],
  [0x1cb, 0x1cb, 0],
  [0x1cc, 0x1cc, -1],
  [0x1f2, 0x1f2, 0],
  [0x1f3, 0x1f3, -1],
  [0x10d0, 0x10fa, 0],
  [0x10fd, 0x10ff, 0],
  [0x1f80, 0x1f87, 8],
  [0x1f88, 0x1f8f, 0],
  [0x1f90, 0x1f97, 8],
  [0x1f98, 0x1f9f, 0],
  [0x1fa0, 0x1fa7, 8],
  [0x1fa8, 0x1faf, 0],
  [0x1fb3, 0x1fb3, 9],
  [0x1fbc, 0x1fbc, 0],
  [0x1fc3, 0x1fc3, 9],
  [0x1fcc, 0x1fcc, 0],
  [0x1ff3, 0x1ff3, 9],
  [0x1ffc, 0x1ffc, 0],
];

function title(ch: string, lang: string | null): string {
  const cp = ch.codePointAt(0) ?? 0;
  for (const [first, last, offset] of TITLECASE) {
    if (cp >= first && cp <= last) return String.fromCodePoint(cp + offset);
  }
  return upper(ch, lang);
}

// Where a word begins for capitalize: after white space, a dash, a quote or
// other punctuation, but not after an apostrophe or a middle dot, which go on
// inside a word ("don't", "l·l"). Firefox 155 and Chromium 153 agree on all
// of that (measured on every punctuation, symbol, separator, mark and number
// code point of the BMP) and differ on brackets, currency and maths symbols
// and on ‘, which start none here.
const capitalize = (text: string, lang: string | null): string =>
  text.replace(
    /(^|(?!['\u2018\u2019\u00b7])[\s\p{Pd}\p{Pi}\p{Pf}\p{Po}])([^\s\p{L}\p{N}]*)(\p{L})/gu,
    (_, sep, lead, ch) => sep + lead + title(ch, lang),
  );

/**
 * Applies the computed text-transform. uppercase may change the length
 * (ß -> SS); the renderer's textLength absorbs that. capitalize title-cases
 * the first letter of every word (see `capitalize`), so "don't" keeps its t.
 * `before` is what is rendered right before `text` (`wordTail` of it is
 * enough): a word goes on across a run's start — a slice cut at the
 * capture edge, a line wrap, an inline boundary like foo<b>bar</b> — and a
 * run starting inside one keeps its case, as on the page.
 */
export function applyTextTransform(
  text: string,
  transform: string,
  lang: string | null,
  before = "",
): string {
  if (transform.includes("uppercase")) return upper(text, lang);
  if (transform.includes("lowercase")) return lower(text, lang);
  if (transform.includes("capitalize")) {
    // Each letter's case depends on what precedes it only, so the prefix
    // comes out the same alone as in front of the text.
    return capitalize(before + text, lang).slice(capitalize(before, lang).length);
  }
  return text;
}

/**
 * The end of `text` up to `end` that decides whether capitalize starts a word
 * right after it: back to and including its last letter, digit or white
 * space. Marks, joiners and apostrophes before it go on inside the word
 * ("x\u0301\u0301" + "ab"), so a fixed number of characters is not enough.
 */
export function wordTail(text: string, end = text.length): string {
  let i = end;
  while (i > 0) {
    const low = text.charCodeAt(i - 1);
    const pair = i > 1 && low >= 0xdc00 && low <= 0xdfff && (text.charCodeAt(i - 2) & 0xfc00) === 0xd800;
    i -= pair ? 2 : 1;
    if (/^[\s\p{L}\p{N}]/u.test(text.slice(i, i + 2))) break;
  }
  return text.slice(i, end);
}

// Private Use Area: icon fonts map their glyphs here; the text is meaningless.
const ICON_ONLY = /^[\s\u{E000}-\u{F8FF}\u{F0000}-\u{FFFFD}\u{100000}-\u{10FFFD}]*$/u;

/** True for text that consists of icon-font code points (and spaces) only. */
export function isIconText(text: string): boolean {
  return ICON_ONLY.test(text) && /\S/.test(text);
}

export interface LineText {
  text: string;
  line: number;
  /** Authored spaces are content (white-space: pre and friends). */
  preserved?: boolean;
}

/**
 * Removes collapsible spaces the browser does not render where runs meet:
 * at the start and end of a line, and the second of two spaces across a run
 * boundary. Runs left empty are dropped. Geometry is untouched because these
 * spaces have zero width in the layout as well.
 */
export function normalizeLines<T extends LineText>(runs: readonly T[]): T[] {
  const out: T[] = [];
  let lineStart = 0;
  const closeLine = () => {
    // Trailing collapsible spaces of the line, possibly across several runs.
    while (out.length > lineStart) {
      const last = out[out.length - 1] as T;
      if (last.preserved) break;
      const text = last.text.replace(/ +$/, "");
      if (text) {
        out[out.length - 1] = { ...last, text };
        break;
      }
      out.pop();
    }
  };
  for (const [i, run] of runs.entries()) {
    if (i > 0 && run.line !== runs[i - 1]?.line) {
      closeLine();
      lineStart = out.length;
    }
    let text = run.text;
    if (!run.preserved) {
      const prev = out.length > lineStart ? out[out.length - 1] : undefined;
      if (!prev || (!prev.preserved && prev.text.endsWith(" "))) text = text.replace(/^ +/, "");
    }
    if (text) out.push(text === run.text ? run : { ...run, text });
  }
  closeLine();
  return out;
}
